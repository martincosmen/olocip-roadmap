# Convertir texto a entero
numero_texto = "25"

numero_entero = int(numero_texto)

print(numero_entero)
print(type(numero_entero))


# Convertir texto decimal a float
numero_decimal_texto = "25.5"

numero_decimal = float(numero_decimal_texto)

print(numero_decimal)
print(type(numero_decimal))


# Convertir float a entero
numero_float = 25.9

numero_int = int(numero_float)

print(numero_int)
print(type(numero_int))


# Convertir número a texto
numero = 25

numero_texto = str(numero)

print(numero_texto)
print(type(numero_texto))