# ==========================================
# BUCLE FOR
# ==========================================

# Recorre elementos de una lista
jugadores = ["Lamine", "Pedri", "Gavi", "Cubarsí"]

for jugador in jugadores:
    print(jugador)


# ==========================================
# BUCLE WHILE
# ==========================================

# Repite mientras se cumpla una condición
jornada = 1

while jornada <= 5:
    print("Jornada", jornada)
    jornada = jornada + 1